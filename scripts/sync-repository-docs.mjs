import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import {
  mkdir,
  readFile,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { basename, dirname, extname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  repositories,
  repositoryDirectoryEnvironmentVariable,
  repositoryGroups,
} from '../docs/repositories.mjs';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docsRoot = resolve(projectRoot, 'src/content/docs/docs');
const assetsRoot = resolve(projectRoot, 'public/repository-assets');
const marker = '<!-- Generated by scripts/sync-repository-docs.mjs. Do not edit. -->';

function shellGit(cwd, ...args) {
  return execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
}

function findRepositoriesRoot() {
  if (process.env.AI_OUTFITTER_REPOS_DIR) {
    return resolve(process.env.AI_OUTFITTER_REPOS_DIR);
  }

  let candidate = projectRoot;
  while (dirname(candidate) !== candidate) {
    if (
      existsSync(resolve(candidate, 'outfitter/README.md')) &&
      existsSync(resolve(candidate, 'actions/README.md'))
    ) {
      return candidate;
    }
    candidate = dirname(candidate);
  }

  const cached = resolve(projectRoot, '.cache/docs-repositories');
  if (existsSync(resolve(cached, 'outfitter/README.md'))) return cached;

  throw new Error(
    'Could not find the AI Outfitter repositories. Set AI_OUTFITTER_REPOS_DIR or run npm run docs:checkout.',
  );
}

const repositoriesRoot = findRepositoriesRoot();

function sourceDirectory(repository) {
  const override = process.env[repositoryDirectoryEnvironmentVariable(repository.name)];
  return resolve(override || repositoriesRoot, override ? '.' : repository.name);
}

function outputRelativePath(repository, sourcePath, repositoryRoot) {
  const sourceRelative = relative(repositoryRoot, sourcePath).split(sep).join('/');
  if (sourceRelative === 'README.md') return `${repository.slug}/index.md`;

  let docsRelative = sourceRelative.replace(/^docs\//, '');
  if (basename(docsRelative).toLowerCase() === 'readme.md') {
    docsRelative = `${dirname(docsRelative)}/index.md`.replace(/^\.\//, '');
  }
  return `${repository.slug}/${docsRelative}`;
}

function routeForOutput(outputRelative) {
  let route = `/docs/${outputRelative.replace(/\.(md|mdx)$/i, '')}`;
  route = route.replace(/\/index$/, '');
  route = route.toLowerCase().replaceAll('.', '');
  return `${route.replace(/\/$/, '')}/`;
}

function splitFrontmatter(markdown) {
  if (!markdown.startsWith('---\n')) return { frontmatter: '', body: markdown };
  const end = markdown.indexOf('\n---\n', 4);
  if (end === -1) return { frontmatter: '', body: markdown };
  return {
    frontmatter: markdown.slice(4, end),
    body: markdown.slice(end + 5),
  };
}

function yamlString(frontmatter, key) {
  const match = frontmatter.match(new RegExp(`^${key}:\\s*["']?(.+?)["']?\\s*$`, 'm'));
  return match?.[1];
}

function titleFromMarkdown(markdown, fallback) {
  const heading = markdown.match(/^#\s+(.+)$/m)?.[1];
  if (heading) return heading.replace(/[*_`]/g, '').trim();
  return fallback
    .replace(/\.(md|mdx)$/i, '')
    .replaceAll(/[-_]/g, ' ')
    .replace(/\b\w/g, (character) => character.toUpperCase());
}

function yamlQuote(value) {
  return JSON.stringify(value.replaceAll(/\s+/g, ' ').trim());
}

function stripMatchingTitle(markdown, title) {
  const match = markdown.match(/^(\s*)#\s+(.+)\n+/);
  if (!match) return markdown;
  const heading = match[2].replace(/[*_`]/g, '').trim();
  return heading === title ? markdown.slice(match[0].length) : markdown;
}

function isExternalUrl(url) {
  return /^(?:[a-z][a-z\d+.-]*:|\/\/|#|\/)/i.test(url);
}

function splitUrl(url) {
  const match = url.match(/^([^?#]*)([?#].*)?$/);
  return { pathname: match?.[1] || '', suffix: match?.[2] || '' };
}

async function rewriteUrl({
  url,
  sourcePath,
  repositoryRoot,
  repository,
  outputs,
  trackedFiles,
}) {
  if (!url || isExternalUrl(url)) return url;
  const { pathname, suffix } = splitUrl(url);
  const decodedPath = decodeURIComponent(pathname);
  const resolvedPath = resolve(dirname(sourcePath), decodedPath);
  if (resolvedPath !== repositoryRoot && !resolvedPath.startsWith(`${repositoryRoot}${sep}`)) {
    return url;
  }

  let targetPath = resolvedPath;
  if (existsSync(targetPath) && (await stat(targetPath)).isDirectory()) {
    const readme = resolve(targetPath, 'README.md');
    if (outputs.has(readme)) targetPath = readme;
  }

  if (outputs.has(targetPath)) return `${routeForOutput(outputs.get(targetPath))}${suffix}`;

  const sourceRelative = relative(repositoryRoot, targetPath).split(sep).join('/');
  if (
    trackedFiles.has(sourceRelative) &&
    existsSync(targetPath) &&
    (await stat(targetPath)).isFile()
  ) {
    const assetTarget = resolve(assetsRoot, repository.slug, sourceRelative);
    await mkdir(dirname(assetTarget), { recursive: true });
    await writeFile(assetTarget, await readFile(targetPath));
    return `/repository-assets/${repository.slug}/${sourceRelative}${suffix}`;
  }

  const sourceUrl = `https://github.com/ai-outfitter/${repository.name}/blob/main/${sourceRelative}`;
  return `${sourceUrl}${suffix}`;
}

async function rewriteMarkdownLinks(markdown, context) {
  const lines = markdown.split('\n');
  let fenced = false;

  for (let index = 0; index < lines.length; index += 1) {
    const trimmed = lines[index].trimStart();
    if (/^(```|~~~)/.test(trimmed)) {
      fenced = !fenced;
      continue;
    }
    if (fenced) continue;

    const replacements = [];
    const patterns = [
      /(!?\[[^\]]*\]\()([^\s)]+)([^)]*\))/g,
      /^(\s*\[[^\]]+\]:\s*)(\S+)(.*)$/g,
      /(<(?:a|img)\b[^>]*?\b(?:href|src)=["'])([^"']+)(["'][^>]*>)/gi,
    ];

    for (const pattern of patterns) {
      for (const match of lines[index].matchAll(pattern)) {
        replacements.push({
          start: match.index + match[1].length,
          end: match.index + match[1].length + match[2].length,
          value: await rewriteUrl({ url: match[2], ...context }),
        });
      }
    }

    for (const replacement of replacements.sort((a, b) => b.start - a.start)) {
      lines[index] =
        lines[index].slice(0, replacement.start) +
        replacement.value +
        lines[index].slice(replacement.end);
    }
  }

  return lines.join('\n');
}

async function buildRepository(repository) {
  const repositoryRoot = sourceDirectory(repository);
  const readme = resolve(repositoryRoot, 'README.md');
  if (!existsSync(readme)) {
    throw new Error(`${repository.name}: missing ${readme}`);
  }

  shellGit(repositoryRoot, 'rev-parse', '--is-inside-work-tree');
  const commit = shellGit(repositoryRoot, 'rev-parse', 'HEAD');
  const trackedFiles = new Set(
    execFileSync('git', ['ls-files', '-z'], { cwd: repositoryRoot, encoding: 'utf8' })
      .split('\0')
      .filter(Boolean),
  );
  const sourcePaths = [...trackedFiles]
    .filter(
      (path) =>
        path === 'README.md' ||
        (/^docs\//.test(path) && ['.md', '.mdx'].includes(extname(path))),
    )
    .map((path) => resolve(repositoryRoot, path))
    .sort();
  const outputs = new Map(
    sourcePaths.map((sourcePath) => [
      sourcePath,
      outputRelativePath(repository, sourcePath, repositoryRoot),
    ]),
  );

  for (const sourcePath of sourcePaths) {
    const sourceRelative = relative(repositoryRoot, sourcePath).split(sep).join('/');
    const outputRelative = outputs.get(sourcePath);
    const outputPath = resolve(docsRoot, outputRelative);
    const source = await readFile(sourcePath, 'utf8');
    const { frontmatter, body } = splitFrontmatter(source);
    const title = yamlString(frontmatter, 'title') || titleFromMarkdown(body, basename(sourcePath));
    const description = yamlString(frontmatter, 'description');
    const lastUpdated = shellGit(
      repositoryRoot,
      'log',
      '-1',
      '--format=%cI',
      '--',
      sourceRelative,
    );
    const rewritten = await rewriteMarkdownLinks(stripMatchingTitle(body, title), {
      sourcePath,
      repositoryRoot,
      repository,
      outputs,
      trackedFiles,
    });
    const sourceUrl = `https://github.com/ai-outfitter/${repository.name}/blob/${commit}/${sourceRelative}`;
    const editUrl = `https://github.com/ai-outfitter/${repository.name}/edit/main/${sourceRelative}`;
    const generatedFrontmatter = [
      '---',
      `title: ${yamlQuote(title)}`,
      description ? `description: ${yamlQuote(description)}` : undefined,
      `editUrl: ${editUrl}`,
      lastUpdated ? `lastUpdated: ${lastUpdated}` : undefined,
      '---',
    ].filter(Boolean);
    const provenance = `> Synced from [\`${repository.name}/${sourceRelative}\`](${sourceUrl}). The repository is the source of truth.`;

    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(
      outputPath,
      `${generatedFrontmatter.join('\n')}\n\n${marker}\n\n${provenance}\n\n${rewritten.trim()}\n`,
    );
  }

  return { repository, count: sourcePaths.length, commit };
}

async function writeProjectIndex(results) {
  const lines = [
    '---',
    'title: Repository documentation',
    'description: Documentation published directly from each AI Outfitter repository.',
    '---',
    '',
    marker,
    '',
    'These pages are built from each repository’s `README.md` and complete `docs/` tree.',
    'Use the source link on any page to inspect the exact commit that was published.',
    '',
    '## Current operating boundaries',
    '',
    '| Surface | Public status |',
    '| --- | --- |',
    '| Outfitter CLI and dashboard-managed `.agents` repositories | Available |',
    '| Headless execution with Actions | Available |',
    '| Long-running event intake with Channels | Alpha |',
    '| Resident execution with Agent Operator | Design stage; not a public onboarding path |',
    '| Durable evidence storage with Pensieve | Design stage |',
    '',
    'These statuses describe public adoption readiness. A repository may publish working code or a versioned artifact before its onboarding path is stable.',
    '',
  ];

  for (const group of repositoryGroups) {
    lines.push(`## ${group}`, '');
    for (const { repository, count } of results.filter(({ repository }) => repository.group === group)) {
      lines.push(
        `- [${repository.title}](/docs/${repository.slug}/) — ${count} source document${count === 1 ? '' : 's'} · [repository](https://github.com/ai-outfitter/${repository.name})`,
      );
    }
    lines.push('');
  }

  await mkdir(resolve(docsRoot, 'projects'), { recursive: true });
  await writeFile(resolve(docsRoot, 'projects/index.md'), `${lines.join('\n').trim()}\n`);
}

await rm(assetsRoot, { recursive: true, force: true });
for (const { slug } of repositories) {
  await rm(resolve(docsRoot, slug), { recursive: true, force: true });
}
await rm(resolve(docsRoot, 'projects'), { recursive: true, force: true });

const results = [];
for (const repository of repositories) results.push(await buildRepository(repository));
await writeProjectIndex(results);

const total = results.reduce((sum, { count }) => sum + count, 0);
console.log(`Synced ${total} canonical documents from ${results.length} repositories.`);
for (const { repository, count, commit } of results) {
  console.log(`- ${repository.name}: ${count} (${commit.slice(0, 12)})`);
}
